//! `revi claim` and `revi status`: the coordination state of the decomp.
//!
//! One file per RVA under `claims/`, so two contributors never edit the same
//! file. `status` renders the totals; the file it writes is generated and is
//! never edited by hand.

use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::check::claimed_rvas;
use victory_map::read_map;

#[derive(serde::Serialize)]
struct Claim {
    rva: u32,
    size: u32,
    chunks: u32,
    status: &'static str,
    owner: String,
    /// ISO date, so stale claims can be aged without git archaeology.
    claimed_at: String,
}

pub fn claim(
    map: &Path,
    decomp: &Path,
    rva: u32,
    size: Option<u32>,
    chunks: u32,
    owner: &str,
) -> Result<()> {
    let extents = read_map(map)?;
    let Some(&mapped) = extents.get(&rva) else {
        bail!(
            "{rva:#08x} is not in {} (run `revi map` again?)",
            map.display()
        );
    };
    let chunks = chunks.max(1);
    let mut span = mapped;
    if chunks > 1 {
        let mut at = rva;
        for _ in 1..chunks {
            let Some(&next) = extents.range(at + 1..).next().map(|(k, _)| k) else {
                bail!("{chunks} chunks run past the end of the map");
            };
            if next != at + extents[&at] {
                bail!("chunks after {at:#08x} are not contiguous");
            }
            span += extents[&next];
            at = next;
        }
    }
    let size = size.unwrap_or(span);
    if size == 0 || (chunks == 1 && size > mapped) || size > span {
        bail!("size {size} outside the claimed {chunks}-chunk span {span}");
    }
    let claims = decomp.join("claims");
    std::fs::create_dir_all(&claims).with_context(|| format!("creating {}", claims.display()))?;
    let path = claims.join(format!("0x{rva:08x}.json"));

    if let Ok(text) = std::fs::read_to_string(&path) {
        let existing: serde_json::Value = serde_json::from_str(&text).unwrap_or_default();
        let status = existing["status"].as_str().unwrap_or("?");
        if status != "stale" {
            bail!(
                "{rva:#08x} is already claimed as {status:?} by {}",
                existing["owner"].as_str().unwrap_or("?")
            );
        }
    }

    let record = Claim {
        rva,
        size,
        chunks,
        status: "claimed",
        owner: owner.to_owned(),
        claimed_at: today(),
    };
    write_json(&path, &record)?;
    let notes = decomp.join("notes").join(format!("0x{rva:08x}.md"));
    if !notes.exists() {
        write_text(
            &notes,
            &format!(
                "# {rva:#08x}\n\nsize {size} of {mapped}\nowner {owner}\n\n\
                 Callers, behaviour, open questions. This file must stand alone:\n\
                 it is what survives if the C is ever pulled.\n"
            ),
        )?;
    }
    println!("claimed {rva:#08x} ({size} bytes) for {owner}");
    Ok(())
}

pub fn status(map: &Path, decomp: &Path) -> Result<()> {
    let extents = read_map(map)?;
    let claimed = claimed_rvas(decomp);
    let mut by_status: std::collections::BTreeMap<String, usize> = Default::default();
    for path in std::fs::read_dir(decomp.join("claims"))?.flatten() {
        let path = path.path();
        if path.file_name().is_some_and(|n| n.to_string_lossy().starts_with('.')) {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue;
        };
        let value: serde_json::Value = serde_json::from_str(&text).unwrap_or_default();
        let status = value["status"].as_str().unwrap_or("unknown").to_owned();
        *by_status.entry(status).or_default() += 1;
    }
    let matching = *by_status.get("matching").unwrap_or(&0);
    let mapped_bytes: u64 = extents.values().map(|&s| u64::from(s)).sum();
    let covered: u64 = claimed
        .iter()
        .filter_map(|rva| extents.get(rva))
        .map(|&s| u64::from(s))
        .sum();
    let percent = if mapped_bytes == 0 {
        0.0
    } else {
        100.0 * covered as f64 / mapped_bytes as f64
    };

    let mut counts: std::collections::BTreeMap<String, usize> = Default::default();
    if let Ok(text) = std::fs::read_to_string(decomp.join("map/candidates.csv")) {
        for line in text.lines().skip(1) {
            if let Some(class) = line.split(',').nth(3) {
                *counts.entry(class.to_owned()).or_default() += 1;
            }
        }
    }

    let mut out = String::from(
        "<!-- generated by `revi status`; do not edit -->\n\
         # Status\n\n",
    );
    out.push_str(&format!(
        "Functions mapped: **{}**  \nClaimed: **{}** ({percent:.3}% of mapped bytes)  \nMatching: **{matching}**\n\n",
        extents.len(),
        claimed.len()
    ));
    for (status, count) in &by_status {
        out.push_str(&format!("* {status}: {count}\n"));
    }
    if !counts.is_empty() {
        out.push_str("\nClasses: ");
        let list: Vec<String> = counts.iter().map(|(k, v)| format!("{k} {v}")).collect();
        out.push_str(&list.join(", "));
        out.push('\n');
    }
    write_text(&decomp.join("STATUS.md"), &out)?;
    println!("{out}");
    Ok(())
}

fn today() -> String {
    // The map is date-stamped by the tool, not by git, so a claim can age.
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    let days = now / 86_400;
    // 1970-01-01 + days, civil-from-days (Howard Hinnant's algorithm).
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 - if month <= 2 { 1 } else { 0 };
    format!("{year:04}-{month:02}-{day:02}")
}

fn write_json<T: serde::Serialize>(path: &Path, value: &T) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let mut text = serde_json::to_string_pretty(value)?;
    text.push('\n');
    write_text(path, &text)
}

fn write_text(path: &Path, text: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}
